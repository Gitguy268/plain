// Package codegen turns checked Plain modules into one JavaScript file.
package codegen

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/Gitguy268/plain/internal/diag"
	"github.com/Gitguy268/plain/internal/syntax"
	"github.com/Gitguy268/plain/internal/types"
)

// Mode says what the bundle does when it runs.
type Mode int

const (
	Run  Mode = iota // call main
	Test             // run the entry module's test blocks
	Lib              // just define everything
)

// Version is written into the header of every bundle.
var Version = "0.1.0"

type gen struct {
	info    *types.Info
	mod     *types.Module
	src     *diag.Source
	out     *strings.Builder
	indent  int
	names   map[*types.Binding]string
	used    map[string]bool
	tmp     int
	imports map[string]string
}

var jsReserved = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`break case catch class const continue debugger default delete do else enum export extends
		false finally for function if import in instanceof new null return super switch this throw true try typeof var void
		while with yield let static implements interface package private protected public await arguments eval undefined NaN
		Infinity globalThis Object Array String Number Boolean Map Set Error Promise Symbol Date JSON Math RegExp Function Proxy
		Reflect console process Some None Ok Err PlainPanic`) {
		jsReserved[w] = true
	}
}

func safe(name string) string {
	if jsReserved[name] {
		return name + "_"
	}
	return name
}

// Bundle writes the whole program: runtime, modules and the line that starts it.
func Bundle(info *types.Info, entry *types.Module, mode Mode, prelude string) string {
	g := &gen{info: info, names: map[*types.Binding]string{}, imports: map[string]string{}}
	var body strings.Builder
	for _, m := range info.Modules {
		if m == info.Core {
			continue
		}
		var mb strings.Builder
		g.out = &mb
		g.mod = m
		g.src = m.File.Src
		if g.module(m, mode == Test && m == entry) {
			body.WriteString(mb.String())
			body.WriteString("\n")
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by Plain %s from %s. Edit the .pln file, not this one.\n", Version, entry.File.Src.Name)
	var keys []string
	for k := range g.imports {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		i := strings.LastIndex(k, "#")
		fmt.Fprintf(&b, "import { %s as %s } from %s;\n", k[i+1:], g.imports[k], jsString(k[:i]))
	}
	b.WriteString(prelude)
	b.WriteString("\n")
	b.WriteString(body.String())
	switch mode {
	case Run:
		if mb, ok := entry.Scope.Lookup("main"); ok && mb.Kind == types.BFn {
			fmt.Fprintf(&b, "$main(%s.main);\n", entry.JSName)
		}
	case Test:
		fmt.Fprintf(&b, "$runTests(%s, %s.$tests);\n", jsString(entry.File.Src.Name), entry.JSName)
	}
	return b.String()
}

func (g *gen) line(format string, args ...any) {
	g.out.WriteString(strings.Repeat("  ", g.indent))
	fmt.Fprintf(g.out, format, args...)
	g.out.WriteString("\n")
}

func (g *gen) loc(sp diag.Span) string { return jsString(g.src.Loc(sp.Start)) }

func (g *gen) fresh(base string) string {
	name := safe(base)
	if !g.used[name] {
		g.used[name] = true
		return name
	}
	for i := 1; ; i++ {
		n := fmt.Sprintf("%s$%d", name, i)
		if !g.used[n] {
			g.used[n] = true
			return n
		}
	}
}

func (g *gen) tmpName(base string) string {
	g.tmp++
	n := fmt.Sprintf("$%s%d", base, g.tmp)
	g.used[n] = true
	return n
}

func (g *gen) declare(n syntax.Node, plain string) string {
	b := g.info.Defs[n]
	name := g.fresh(plain)
	if b != nil {
		g.names[b] = name
	}
	return name
}

// module emits one module as an object built by an arrow function. It returns false when there is nothing to emit.
func (g *gen) module(m *types.Module, tests bool) bool {
	f := m.File
	var exports []string
	top := map[string]bool{}
	for _, it := range f.Items {
		switch d := it.(type) {
		case *syntax.FnDecl:
			top[safe(d.Name)] = true
		case *syntax.LetDecl:
			top[safe(d.Name)] = true
		case *syntax.ExternDecl:
			if !strings.HasPrefix(d.Target, "$") {
				top[safe(d.Name)] = true
			}
		case *syntax.TypeDecl:
			for _, v := range d.Variants {
				top[safe(v.Name)] = true
			}
		}
	}
	hasTests := false
	for _, it := range f.Items {
		if _, ok := it.(*syntax.TestDecl); ok {
			hasTests = true
		}
	}
	if len(top) == 0 && !(tests && hasTests) && !tests {
		return false
	}
	g.line("const %s = (() => {", m.JSName)
	g.indent++
	newUsed := func() {
		g.used = map[string]bool{}
		for k := range top {
			g.used[k] = true
		}
	}
	// constructors first, so everything below can use them
	for _, it := range f.Items {
		d, ok := it.(*syntax.TypeDecl)
		if !ok {
			continue
		}
		for _, v := range d.Variants {
			name := safe(v.Name)
			exports = append(exports, name)
			if len(v.Fields) == 0 {
				g.line("const %s = Object.freeze({ $: %s });", name, jsString(v.Name))
				continue
			}
			var ps []string
			for i := range v.Fields {
				ps = append(ps, fmt.Sprintf("_%d", i))
			}
			g.line("const %s = (%s) => ({ $: %s, %s });", name, strings.Join(ps, ", "), jsString(v.Name), strings.Join(ps, ", "))
		}
	}
	for _, it := range f.Items {
		switch d := it.(type) {
		case *syntax.ExternDecl:
			if strings.HasPrefix(d.Target, "$") {
				continue
			}
			newUsed()
			g.extern(d)
			exports = append(exports, safe(d.Name))
		case *syntax.FnDecl:
			newUsed()
			g.fn(d)
			exports = append(exports, safe(d.Name))
		}
	}
	for _, it := range f.Items {
		if d, ok := it.(*syntax.LetDecl); ok {
			newUsed()
			g.line("const %s = %s;", safe(d.Name), g.expr(d.Value))
			exports = append(exports, safe(d.Name))
		}
	}
	if tests {
		g.line("const $tests = [")
		g.indent++
		for _, it := range f.Items {
			d, ok := it.(*syntax.TestDecl)
			if !ok {
				continue
			}
			newUsed()
			g.line("[%s, () => {", jsString(d.Name))
			g.indent++
			g.tail(d.Body, discard)
			g.indent--
			g.line("}],")
		}
		g.indent--
		g.line("];")
		exports = append(exports, "$tests")
	}
	g.line("return { %s };", strings.Join(exports, ", "))
	g.indent--
	g.line("})();")
	return true
}

var targetPath = regexp.MustCompile(`^[A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)*$`)
var targetImport = regexp.MustCompile(`^[^#\s]+#[A-Za-z_$][\w$]*$`)

func (g *gen) extern(d *syntax.ExternDecl) {
	var ps []string
	for _, p := range d.Params {
		ps = append(ps, g.fresh(p.Name))
	}
	target := d.Target
	if targetImport.MatchString(target) {
		alias, ok := g.imports[target]
		if !ok {
			alias = fmt.Sprintf("$import%d", len(g.imports)+1)
			g.imports[target] = alias
		}
		target = alias
	}
	call := fmt.Sprintf("%s(%s)", target, strings.Join(ps, ", "))
	b := g.mod.Scope.MustLookup(d.Name)
	ret := b.Scheme.Type.(*types.TFn).Ret
	g.line("function %s(%s) {", safe(d.Name), strings.Join(ps, ", "))
	g.indent++
	if types.IsCon(ret, "Unit") {
		g.line("%s;", call)
	} else {
		g.line("return %s;", wrapExtern(call, ret, d.Name))
	}
	g.indent--
	g.line("}")
}

// ValidTarget reports whether an extern target is something the code generator can call.
func ValidTarget(t string) bool { return targetPath.MatchString(t) || targetImport.MatchString(t) }

func wrapExtern(call string, t types.Type, name string) string {
	switch {
	case types.IsCon(t, "Option"):
		return fmt.Sprintf("$ext_opt(%s)", call)
	case types.IsCon(t, "Result"):
		inner := types.Prune(t).(*types.TCon).Args[0]
		if types.IsCon(inner, "Unit") {
			return fmt.Sprintf("$ext_res(() => { %s; })", call)
		}
		return fmt.Sprintf("$ext_res(() => %s)", wrapExtern(call, inner, name))
	case types.IsCon(t, "Int"):
		return fmt.Sprintf("$ext_int(%s, %s)", call, jsString(name))
	}
	return fmt.Sprintf("$ext_val(%s, %s)", call, jsString(name))
}

func (g *gen) params(ps []*syntax.Param) string {
	var out []string
	for _, p := range ps {
		name := "_"
		if p.Name != "_" {
			name = g.declare(p, p.Name)
		} else {
			name = g.tmpName("unused")
		}
		if p.Default != nil {
			name += " = " + g.expr(p.Default)
		}
		out = append(out, name)
	}
	return strings.Join(out, ", ")
}

func (g *gen) fn(d *syntax.FnDecl) {
	ps := g.params(d.Params)
	g.line("function %s(%s) {", safe(d.Name), ps)
	g.indent++
	b := g.mod.Scope.MustLookup(d.Name)
	unit := types.IsCon(b.Scheme.Type.(*types.TFn).Ret, "Unit")
	g.body(d.Body, unit)
	g.indent--
	g.line("}")
}

// body emits a function body, catching the early return that ? uses.
func (g *gen) body(e syntax.Expr, unit bool) {
	m := ret
	if unit {
		m = discard
	}
	if !hasTry(e) {
		g.tail(e, m)
		return
	}
	g.line("try {")
	g.indent++
	g.tail(e, m)
	g.indent--
	g.line("} catch ($e) {")
	g.line("  if ($e instanceof $Early) return $e.v;")
	g.line("  throw $e;")
	g.line("}")
}

// ---- statements and tail positions ----

type mode struct {
	kind   int // 0 return, 1 discard, 2 assign
	target string
}

var (
	ret     = mode{kind: 0}
	discard = mode{kind: 1}
)

func assign(t string) mode { return mode{kind: 2, target: t} }

func (g *gen) finish(v string, m mode, pure bool) {
	switch m.kind {
	case 0:
		g.line("return %s;", v)
	case 1:
		if !pure {
			g.line("%s;", v)
		}
	case 2:
		g.line("%s = %s;", m.target, v)
	}
}

func unparen(e syntax.Expr) syntax.Expr {
	for {
		p, ok := e.(*syntax.Paren)
		if !ok {
			return e
		}
		e = p.X
	}
}

// tail emits an expression whose value goes to m.
func (g *gen) tail(e syntax.Expr, m mode) {
	switch n := unparen(e).(type) {
	case *syntax.Block:
		for i, s := range n.Stmts {
			if i == len(n.Stmts)-1 {
				if es, ok := s.(*syntax.ExprStmt); ok {
					g.tail(es.X, m)
					return
				}
			}
			g.stmt(s)
		}
		if m.kind == 0 && len(n.Stmts) == 0 {
			g.line("return;")
		}
	case *syntax.If:
		g.line("if (%s) {", stripOuter(g.expr(n.Cond)))
		g.indent++
		if n.Else == nil {
			g.tail(n.Then, discard)
		} else {
			g.tail(n.Then, m)
		}
		g.indent--
		if n.Else != nil {
			g.line("} else {")
			g.indent++
			g.tail(n.Else, m)
			g.indent--
		}
		g.line("}")
	case *syntax.Match:
		g.match(n, m)
	default:
		v := g.expr(e)
		g.finish(stripOuter(v), m, isPure(unparen(e)))
	}
}

func isPure(e syntax.Expr) bool {
	switch e.(type) {
	case *syntax.Ident, *syntax.IntLit, *syntax.FloatLit, *syntax.BoolLit, *syntax.StringLit, *syntax.CtorRef:
		return true
	}
	return false
}

func complex(e syntax.Expr) bool {
	switch n := unparen(e).(type) {
	case *syntax.Match:
		return true
	case *syntax.Block:
		return !(len(n.Stmts) == 1 && syntax.BlockValue(n) != nil && !complex(syntax.BlockValue(n)))
	case *syntax.If:
		return !simpleIf(n)
	}
	return false
}

func simpleIf(n *syntax.If) bool {
	if n.Else == nil {
		return false
	}
	one := func(b *syntax.Block) bool {
		return len(b.Stmts) == 1 && syntax.BlockValue(b) != nil && !complex(syntax.BlockValue(b))
	}
	if !one(n.Then) {
		return false
	}
	switch e := n.Else.(type) {
	case *syntax.Block:
		return one(e)
	case *syntax.If:
		return simpleIf(e)
	}
	return false
}

func (g *gen) stmt(s syntax.Stmt) {
	switch n := s.(type) {
	case *syntax.LetStmt:
		if n.Name == "_" {
			g.tail(n.Value, discard)
			return
		}
		if complex(n.Value) {
			name := g.declare(n, n.Name)
			g.line("let %s;", name)
			g.tail(n.Value, assign(name))
			return
		}
		v := stripOuter(g.expr(n.Value)) // evaluate before the name exists, so `let x = x + 1` sees the old x
		name := g.declare(n, n.Name)
		kw := "const"
		if n.Mutable {
			kw = "let"
		}
		g.line("%s %s = %s;", kw, name, v)
	case *syntax.AssignStmt:
		b := g.info.Refs[n]
		name := g.names[b]
		if n.Op == "=" {
			if complex(n.Value) {
				g.tail(n.Value, assign(name))
				return
			}
			g.line("%s = %s;", name, stripOuter(g.expr(n.Value)))
			return
		}
		op := n.Op[:1]
		v := g.expr(n.Value)
		if types.IsCon(b.Type, "Int") {
			g.line("%s = $int(%s %s %s, %s);", name, name, op, v, g.loc(n.Sp))
		} else {
			g.line("%s %s= %s;", name, op, stripOuter(v))
		}
	case *syntax.ExprStmt:
		g.tail(n.X, discard)
	case *syntax.ForStmt:
		iter := stripOuter(g.expr(n.Iter))
		name := g.declare(n, n.Var)
		g.line("for (const %s of %s) {", name, iter)
		g.indent++
		g.tail(n.Body, discard)
		g.indent--
		g.line("}")
	case *syntax.WhileStmt:
		g.line("while (%s) {", stripOuter(g.expr(n.Cond)))
		g.indent++
		g.tail(n.Body, discard)
		g.indent--
		g.line("}")
	case *syntax.AssertStmt:
		src := jsString(g.src.Text[n.X.Span().Start:n.X.Span().End])
		if b, ok := unparen(n.X).(*syntax.Binary); ok && (b.Op == "==" || b.Op == "!=") {
			g.line("$assertEq(%s, %s, %v, %s, %s);", stripOuter(g.expr(b.L)), stripOuter(g.expr(b.R)), b.Op == "==", src, g.loc(n.Sp))
			return
		}
		g.line("$assert(%s, %s, %s);", stripOuter(g.expr(n.X)), src, g.loc(n.Sp))
	}
}

// ---- match ----

func (g *gen) match(n *syntax.Match, m mode) {
	subj := stripOuter(g.expr(n.Subject))
	if _, ok := unparen(n.Subject).(*syntax.Ident); !ok {
		t := g.tmpName("subject")
		g.line("const %s = %s;", t, subj)
		subj = t
	}
	label := ""
	if m.kind != 0 {
		label = g.tmpName("match")
		g.line("%s: {", label)
		g.indent++
	}
	brk := func() {
		if label != "" {
			g.line("break %s;", label)
		}
	}
	for _, arm := range n.Arms {
		var conds []string
		var binds [][2]string
		g.patCode(arm.Pat, subj, &conds, &binds)
		open := 0
		if len(conds) > 0 {
			g.line("if (%s) {", strings.Join(conds, " && "))
			g.indent++
			open++
		} else if len(binds) > 0 || arm.Guard != nil || label != "" {
			g.line("{")
			g.indent++
			open++
		}
		for _, b := range binds {
			g.line("const %s = %s;", b[0], b[1])
		}
		if arm.Guard != nil {
			g.line("if (%s) {", stripOuter(g.expr(arm.Guard)))
			g.indent++
			open++
		}
		g.tail(arm.Body, m)
		brk()
		for ; open > 0; open-- {
			g.indent--
			g.line("}")
		}
	}
	if label != "" {
		g.indent--
		g.line("}")
	}
}

func (g *gen) patCode(p syntax.Pattern, access string, conds *[]string, binds *[][2]string) {
	switch n := p.(type) {
	case *syntax.PWild:
	case *syntax.PBind:
		*binds = append(*binds, [2]string{g.declare(n, n.Name), access})
	case *syntax.PLit:
		switch n.Kind {
		case syntax.String:
			*conds = append(*conds, fmt.Sprintf("%s === %s", access, jsString(n.Str)))
		default:
			*conds = append(*conds, fmt.Sprintf("%s === %s", access, strings.ReplaceAll(n.Text, "_", "")))
		}
	case *syntax.PCtor:
		*conds = append(*conds, fmt.Sprintf("%s.$ === %s", access, jsString(n.Name)))
		for i, a := range n.Args {
			g.patCode(a, fmt.Sprintf("%s._%d", access, i), conds, binds)
		}
	case *syntax.PList:
		op := "==="
		if n.HasRest {
			op = ">="
		}
		*conds = append(*conds, fmt.Sprintf("%s.length %s %d", access, op, len(n.Elems)))
		for i, e := range n.Elems {
			g.patCode(e, fmt.Sprintf("%s[%d]", access, i), conds, binds)
		}
		if n.Rest != "" {
			*binds = append(*binds, [2]string{g.declare(n, n.Rest), fmt.Sprintf("%s.slice(%d)", access, len(n.Elems))})
		}
	}
}

// ---- expressions ----

func stripOuter(s string) string {
	if len(s) < 2 || s[0] != '(' || s[len(s)-1] != ')' {
		return s
	}
	depth := 0
	inStr := byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		if inStr != 0 {
			if c == '\\' {
				i++
			} else if c == inStr {
				inStr = 0
			}
			continue
		}
		switch c {
		case '"', '`', '\'':
			inStr = c
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 && i != len(s)-1 {
				return s
			}
		}
	}
	return s[1 : len(s)-1]
}

func (g *gen) ref(b *types.Binding) string {
	switch b.Kind {
	case types.BLocal:
		if n, ok := g.names[b]; ok {
			return n
		}
		return safe(b.Name)
	case types.BExtern:
		if strings.HasPrefix(b.Extern.Target, "$") {
			return b.Extern.Target
		}
	case types.BCtor:
		if b.Module == g.info.Core {
			return b.Name
		}
	}
	if b.Module == g.mod {
		return safe(b.Name)
	}
	return b.Module.JSName + "." + safe(b.Name)
}

func (g *gen) typeOf(e syntax.Expr) types.Type { return g.info.Types[e] }

func primitive(t types.Type) bool {
	return types.IsCon(t, "Int") || types.IsCon(t, "Float") || types.IsCon(t, "String") || types.IsCon(t, "Bool") || types.IsCon(t, "Unit")
}

func (g *gen) expr(e syntax.Expr) string {
	switch n := e.(type) {
	case *syntax.IntLit:
		return strings.ReplaceAll(n.Text, "_", "")
	case *syntax.FloatLit:
		return strings.ReplaceAll(n.Text, "_", "")
	case *syntax.BoolLit:
		if n.Value {
			return "true"
		}
		return "false"
	case *syntax.StringLit:
		hasExpr := false
		for _, p := range n.Parts {
			if p.X != nil {
				hasExpr = true
			}
		}
		if !hasExpr {
			var b strings.Builder
			for _, p := range n.Parts {
				b.WriteString(p.Lit)
			}
			return jsString(b.String())
		}
		var b strings.Builder
		b.WriteByte('`')
		for _, p := range n.Parts {
			if p.X == nil {
				b.WriteString(templateEscape(p.Lit))
				continue
			}
			v := stripOuter(g.expr(p.X))
			if d := g.floatDesc(g.typeOf(p.X), 0); d != "" {
				v = "$show(" + v + ", " + d + ")"
			} else if !primitive(g.typeOf(p.X)) {
				v = "$show(" + v + ")"
			}
			b.WriteString("${" + v + "}")
		}
		b.WriteByte('`')
		return b.String()
	case *syntax.Paren:
		return "(" + stripOuter(g.expr(n.X)) + ")"
	case *syntax.Ident:
		if b := g.info.Refs[n]; b != nil {
			return g.ref(b)
		}
		return safe(n.Name)
	case *syntax.CtorRef:
		if b := g.info.Refs[n]; b != nil {
			return g.ref(b)
		}
		return safe(n.Name)
	case *syntax.Field:
		if b := g.info.Refs[n]; b != nil {
			return g.ref(b)
		}
		return g.atom(n.X) + "." + n.Name
	case *syntax.Call:
		return g.call(n)
	case *syntax.Binary:
		return g.binary(n)
	case *syntax.Unary:
		return "(" + n.Op + g.atom(n.X) + ")"
	case *syntax.If:
		if simpleIf(n) {
			return g.ternary(n)
		}
		return g.iife(e)
	case *syntax.Match:
		return g.iife(e)
	case *syntax.Block:
		if len(n.Stmts) == 0 {
			return "undefined"
		}
		if v := syntax.BlockValue(n); v != nil && len(n.Stmts) == 1 {
			return g.expr(v)
		}
		return g.iife(e)
	case *syntax.Lambda:
		return g.lambda(n)
	case *syntax.RecordLit:
		var parts []string
		if n.Base != nil {
			parts = append(parts, "..."+g.atom(n.Base))
		}
		for _, f := range n.Fields {
			parts = append(parts, f.Name+": "+stripOuter(g.expr(f.Value)))
		}
		if len(parts) == 0 {
			return "({})"
		}
		return "({ " + strings.Join(parts, ", ") + " })"
	case *syntax.ListLit:
		var parts []string
		for _, x := range n.Elems {
			parts = append(parts, stripOuter(g.expr(x)))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case *syntax.Try:
		return "$try(" + stripOuter(g.expr(n.X)) + ")"
	}
	return "undefined"
}

// atom wraps an expression in parentheses unless it already is a simple value.
func (g *gen) atom(e syntax.Expr) string {
	s := g.expr(e)
	switch unparen(e).(type) {
	case *syntax.Ident, *syntax.Field, *syntax.Call, *syntax.CtorRef, *syntax.ListLit, *syntax.StringLit, *syntax.BoolLit, *syntax.IntLit, *syntax.FloatLit:
		return s
	}
	if strings.HasPrefix(s, "(") && stripOuter(s) != s {
		return s
	}
	return "(" + s + ")"
}

func (g *gen) ternary(n *syntax.If) string {
	then := stripOuter(g.expr(syntax.BlockValue(n.Then)))
	var els string
	switch e := n.Else.(type) {
	case *syntax.Block:
		els = stripOuter(g.expr(syntax.BlockValue(e)))
	case *syntax.If:
		els = stripOuter(g.ternary(e))
	}
	return fmt.Sprintf("(%s ? %s : %s)", stripOuter(g.expr(n.Cond)), then, els)
}

// iife turns statements into an expression by wrapping them in a function that is called at once.
func (g *gen) iife(e syntax.Expr) string {
	saved, savedIndent := g.out, g.indent
	var b strings.Builder
	g.out = &b
	g.indent = savedIndent + 1
	g.tail(e, ret)
	g.out, g.indent = saved, savedIndent
	return "(() => {\n" + b.String() + strings.Repeat("  ", savedIndent) + "})()"
}

func (g *gen) lambda(n *syntax.Lambda) string {
	ps := g.params(n.Params)
	t, _ := g.typeOf(n).(*types.TFn)
	unit := t != nil && types.IsCon(t.Ret, "Unit")
	if _, isBlock := n.Body.(*syntax.Block); !isBlock && !hasTry(n.Body) && !complex(n.Body) {
		body := stripOuter(g.expr(n.Body))
		if strings.HasPrefix(body, "{") {
			body = "(" + body + ")"
		}
		return fmt.Sprintf("(%s) => %s", ps, body)
	}
	saved, savedIndent := g.out, g.indent
	var b strings.Builder
	g.out = &b
	g.indent = savedIndent + 1
	g.body(n.Body, unit)
	g.out, g.indent = saved, savedIndent
	return fmt.Sprintf("(%s) => {\n%s%s}", ps, b.String(), strings.Repeat("  ", savedIndent))
}

func (g *gen) call(n *syntax.Call) string {
	var args []string
	for _, a := range n.Args {
		args = append(args, stripOuter(g.expr(a)))
	}
	callee := ""
	switch f := unparen(n.Fn).(type) {
	case *syntax.Ident, *syntax.Field, *syntax.CtorRef:
		callee = g.expr(f)
		if b := g.info.Refs[f]; b != nil && b.Kind == types.BExtern && (b.Extern.Target == "$panic" || b.Extern.Target == "$div") {
			args = append(args, g.loc(n.Sp))
		}
		if b := g.info.Refs[f]; b != nil && b.Kind == types.BExtern && (b.Extern.Target == "$print" || b.Extern.Target == "$show") && len(n.Args) == 1 {
			if d := g.floatDesc(g.typeOf(n.Args[0]), 0); d != "" {
				args = append(args, d)
			}
		}
	default:
		callee = g.atom(n.Fn)
	}
	return callee + "(" + strings.Join(args, ", ") + ")"
}

func (g *gen) binary(n *syntax.Binary) string {
	if n.Op == "|>" {
		if c := g.info.Pipes[n]; c != nil {
			return g.call(c)
		}
	}
	l, r := g.atom(n.L), g.atom(n.R)
	lt := g.typeOf(n.L)
	isInt := types.IsCon(lt, "Int")
	switch n.Op {
	case "+", "-", "*":
		if isInt {
			return fmt.Sprintf("$int(%s %s %s, %s)", l, n.Op, r, g.loc(n.OpSp))
		}
		return fmt.Sprintf("(%s %s %s)", l, n.Op, r)
	case "/":
		return fmt.Sprintf("(%s / %s)", l, r)
	case "%":
		return fmt.Sprintf("$mod(%s, %s, %s)", l, r, g.loc(n.OpSp))
	case "++":
		if types.IsCon(lt, "List") {
			return fmt.Sprintf("[...%s, ...%s]", l, r)
		}
		return fmt.Sprintf("(%s + %s)", l, r)
	case "==", "!=":
		if primitive(lt) {
			return fmt.Sprintf("(%s %s= %s)", l, n.Op, r)
		}
		if n.Op == "!=" {
			return fmt.Sprintf("!$eq(%s, %s)", stripOuter(l), stripOuter(r))
		}
		return fmt.Sprintf("$eq(%s, %s)", stripOuter(l), stripOuter(r))
	}
	return fmt.Sprintf("(%s %s %s)", l, n.Op, r)
}

// ---- helpers ----

func jsString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case ' ':
			b.WriteString(` `)
		case ' ':
			b.WriteString(` `)
		default:
			if r < 0x20 {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func templateEscape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, "`", "\\`")
	s = strings.ReplaceAll(s, "${", "\\${")
	s = strings.ReplaceAll(s, "\r", `\r`)
	return s
}

// hasTry reports whether ? appears in e outside nested function values.
func hasTry(e syntax.Expr) bool {
	found := false
	var walkE func(syntax.Expr)
	var walkS func(syntax.Stmt)
	walkE = func(e syntax.Expr) {
		if found || e == nil {
			return
		}
		switch n := e.(type) {
		case *syntax.Try:
			found = true
		case *syntax.StringLit:
			for _, p := range n.Parts {
				walkE(p.X)
			}
		case *syntax.Paren:
			walkE(n.X)
		case *syntax.Call:
			walkE(n.Fn)
			for _, a := range n.Args {
				walkE(a)
			}
		case *syntax.Binary:
			walkE(n.L)
			walkE(n.R)
		case *syntax.Unary:
			walkE(n.X)
		case *syntax.If:
			walkE(n.Cond)
			walkE(n.Then)
			walkE(n.Else)
		case *syntax.Match:
			walkE(n.Subject)
			for _, a := range n.Arms {
				walkE(a.Guard)
				walkE(a.Body)
			}
		case *syntax.Block:
			for _, s := range n.Stmts {
				walkS(s)
			}
		case *syntax.Field:
			walkE(n.X)
		case *syntax.RecordLit:
			walkE(n.Base)
			for _, f := range n.Fields {
				walkE(f.Value)
			}
		case *syntax.ListLit:
			for _, x := range n.Elems {
				walkE(x)
			}
		}
	}
	walkS = func(s syntax.Stmt) {
		switch n := s.(type) {
		case *syntax.LetStmt:
			walkE(n.Value)
		case *syntax.AssignStmt:
			walkE(n.Value)
		case *syntax.ExprStmt:
			walkE(n.X)
		case *syntax.ForStmt:
			walkE(n.Iter)
			walkE(n.Body)
		case *syntax.WhileStmt:
			walkE(n.Cond)
			walkE(n.Body)
		case *syntax.AssertStmt:
			walkE(n.X)
		}
	}
	walkE(e)
	return found
}

// floatDesc describes where Floats sit inside a type, so the runtime can print 2.0 as "2.0".
// It returns "" when the type holds no Floats.
func (g *gen) floatDesc(t types.Type, depth int) string {
	if depth > 6 {
		return ""
	}
	tc, ok := types.Prune(t).(*types.TCon)
	if ok && tc.Rigid {
		return ""
	}
	switch t := types.Prune(t).(type) {
	case *types.TCon:
		switch t.Key {
		case "Float":
			return `"f"`
		case "List":
			if d := g.floatDesc(t.Args[0], depth+1); d != "" {
				return `["L", ` + d + `]`
			}
			return ""
		case "Dict":
			k, v := g.floatDesc(t.Args[0], depth+1), g.floatDesc(t.Args[1], depth+1)
			if k == "" && v == "" {
				return ""
			}
			return `["D", ` + orZero(k) + `, ` + orZero(v) + `]`
		}
		u, ok := g.info.Unions[t.Key]
		if !ok {
			return ""
		}
		var parts []string
		for _, ct := range u.Ctors {
			var fs []string
			any := false
			for _, f := range types.CtorFields(ct, t.Args) {
				d := g.floatDesc(f, depth+1)
				if d != "" {
					any = true
				}
				fs = append(fs, orZero(d))
			}
			if any {
				parts = append(parts, ct.Name+": ["+strings.Join(fs, ", ")+"]")
			}
		}
		if len(parts) == 0 {
			return ""
		}
		return `["U", { ` + strings.Join(parts, ", ") + ` }]`
	case *types.TRecord:
		var parts []string
		for i, n := range t.Names {
			if d := g.floatDesc(t.Types[i], depth+1); d != "" {
				parts = append(parts, n+": "+d)
			}
		}
		if len(parts) == 0 {
			return ""
		}
		return `["R", { ` + strings.Join(parts, ", ") + ` }]`
	}
	return ""
}

func orZero(s string) string {
	if s == "" {
		return "0"
	}
	return s
}
